// 纳斯塔星球上的埃尔夫族守护魔幻森林，蒙斯特族为掠夺资源而发动入侵。
// 冒险模式与BOSS挑战是两个独立系统，仅通过等级/冒险进度/主线完成度解锁。
// 任务文案统一使用“击败”，不使用“击杀”，也不把整个蒙斯特族当作刷怪计数目标。

const q = (id, name, desc, story, goal, event, extra = {}) => ({
  id, name, desc, story, goal, event, ...extra,
});

function chain(rows, prefix, economy = {}) {
  return rows.map((row, index) => {
    const [name, desc, story, goal, event, extra = {}] = row;
    const base = typeof economy === 'function' ? economy(index) : economy;
    return q(`${prefix}${index + 1}`, name, desc, story, goal, event, {
      ...(index > 0 ? { requires: `${prefix}${index}` } : {}),
      ...base,
      ...extra,
    });
  });
}

